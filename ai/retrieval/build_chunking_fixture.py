def validate_record(record: dict) -> None:
    required_fields = {
        "source_id",
        "source_type",
        "version",
        "pii_status",
        "title",
        "content",
    }

    missing_fields = [
        field
        for field in required_fields
        if field not in record
    ]

    if missing_fields:
        raise ValueError(
            f"Missing required fields: {sorted(missing_fields)}"
        )

    if record["source_type"] not in {"PRODUCT", "POLICY"}:
        raise ValueError(
            f"Unsupported source_type: {record['source_type']}"
        )

    if not isinstance(record["version"], str) or not record["version"].strip():
        raise ValueError("version must be a non-empty string")

    if record["pii_status"] != "CLEAN":
        raise ValueError(
            f"pii_status must be CLEAN: {record['source_id']}"
        )

    if not isinstance(record["source_id"], str) or not record["source_id"].strip():
        raise ValueError("source_id must be a non-empty string")

    if not isinstance(record["title"], str) or not record["title"].strip():
        raise ValueError(
            f"title must be non-empty: {record['source_id']}"
        )

    if not isinstance(record["content"], str) or not record["content"].strip():
        raise ValueError(
            f"content must be non-empty: {record['source_id']}"
        )


def write_jsonl(
    records: list[dict],
    output_path: Path,
) -> None:
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with output_path.open(
        "w",
        encoding="utf-8",
        newline="\n",
    ) as file:
        for record in records:
            file.write(
                json.dumps(
                    record,
                    ensure_ascii=False,
                    sort_keys=True,
                )
            )
            file.write("\n")


